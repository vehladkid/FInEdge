import { describe, it, expect, vi, beforeEach } from "vitest";
import { render, screen } from "@testing-library/react";
import { MemoryRouter } from "react-router-dom";
import { AuthProvider } from "../../src/contexts/AuthContext.jsx";
import Dashboard from "../../src/pages/Dashboard.jsx";
import Budget from "../../src/pages/Budget.jsx";
import { ApiError } from "../../src/services/api.js";
import * as finance from "../../src/services/finance.js";

vi.mock("../../src/services/finance.js");
// Recharts needs real layout; the charts are covered by the Playwright suite.
vi.mock("recharts", async () => {
  const Stub = ({ children }) => <div>{children}</div>;
  const names = ["ResponsiveContainer", "BarChart", "Bar", "XAxis", "YAxis", "Tooltip", "Legend", "PieChart", "Pie", "Cell", "LineChart", "Line"];
  return Object.fromEntries(names.map((n) => [n, Stub]));
});

const renderPage = (ui) => render(<MemoryRouter><AuthProvider>{ui}</AuthProvider></MemoryRouter>);
beforeEach(() => vi.resetAllMocks());

const empty = { balance: 0, month: { income: 0, expenses: 0, savingsRate: null }, spendingByCategory: [], recentTransactions: [], budgets: [], hasData: false };

describe("Dashboard", () => {
  it("shows a loading state, then an empty state with zeros and no invented values", async () => {
    finance.getDashboard.mockResolvedValue(empty);
    finance.getInsights.mockResolvedValue({ source: "rule-based", insights: [{ id: "no-insights", severity: "info", message: "Add some transactions this month to start receiving insights." }] });
    renderPage(<Dashboard />);
    expect(screen.getByRole("status")).toBeInTheDocument();
    expect(await screen.findByText(/You have no transactions yet/)).toBeInTheDocument();
    expect(screen.getByTestId("card-Total Balance")).toHaveTextContent("$0.00");
    expect(screen.getByText("No expenses recorded this month.")).toBeInTheDocument();
    expect(await screen.findByText(/Add some transactions this month/)).toBeInTheDocument();
  });

  it("renders real totals, recent transactions and budget status", async () => {
    finance.getDashboard.mockResolvedValue({
      balance: 1820, month: { income: 3000, expenses: 1180, savingsRate: 60.7 },
      spendingByCategory: [{ categoryId: 1, name: "Food", total: 410, share: 100 }],
      recentTransactions: [{ id: 9, type: "expense", amount: 42.1, description: "Grocery", categoryName: "Food", date: "2026-05-04" }],
      budgets: [{ id: 1, category: "Food", amount: 400, spent: 340, percentUsed: 85, status: "warning" }],
      hasData: true,
    });
    finance.getInsights.mockResolvedValue({ source: "ai", insights: [{ id: "ai-0", severity: "warning", message: "Dining is up" }] });
    renderPage(<Dashboard />);
    expect(await screen.findByTestId("card-Total Balance")).toHaveTextContent("$1,820.00");
    expect(screen.getByTestId("card-Income (Month)")).toHaveTextContent("$3,000.00");
    expect(screen.getByTestId("card-Expenses (Month)")).toHaveTextContent("$1,180.00");
    expect(screen.getByLabelText("Recent transactions")).toHaveTextContent("Grocery");
    expect(screen.getByLabelText("Recent transactions")).toHaveTextContent("−$42.10");
    expect(screen.getByLabelText("Budget status")).toHaveTextContent("$340.00 / $400.00");
    expect(await screen.findByText("Dining is up")).toBeInTheDocument();
    expect(screen.getByText("Generated by an AI model")).toBeInTheDocument();
  });

  it("shows an error with a retry when the API fails", async () => {
    finance.getDashboard.mockRejectedValue(new ApiError(500, "INTERNAL_ERROR", "Something went wrong"));
    renderPage(<Dashboard />);
    expect(await screen.findByRole("alert")).toHaveTextContent("Something went wrong");
    expect(screen.getByRole("button", { name: "Retry" })).toBeInTheDocument();
  });
});

describe("Budget page", () => {
  it("shows computed status from the backend, including exceeded budgets", async () => {
    finance.getBudgets.mockResolvedValue([
      { id: 1, category: "Food", categoryId: 1, amount: 400, spent: 450, remaining: -50, percentUsed: 112.5, exceeded: true, status: "exceeded", period: "monthly", startDate: "2026-05-01", endDate: "2026-05-31" },
    ]);
    finance.getCategories.mockResolvedValue([{ id: 1, name: "Food", type: "expense" }]);
    renderPage(<Budget />);
    expect(await screen.findByText("$450.00 / $400.00")).toBeInTheDocument();
    expect(screen.getByText(/112.5% used · \$50.00 over budget/)).toBeInTheDocument();
    expect(screen.getByRole("progressbar", { name: "Food budget used" })).toHaveAttribute("aria-valuenow", "100");
  });

  it("shows the empty state", async () => {
    finance.getBudgets.mockResolvedValue([]);
    finance.getCategories.mockResolvedValue([{ id: 1, name: "Food", type: "expense" }]);
    renderPage(<Budget />);
    expect(await screen.findByText(/No budgets yet/)).toBeInTheDocument();
  });
});
