import Card from "./ui/Card";
import { ErrorMessage, Loading } from "./ui/States";
import { useAsync } from "../hooks/useAsync";
import { getInsights } from "../services/finance";

const DOT = { critical: "text-rose-400", warning: "text-amber-400", positive: "text-emerald-400", info: "text-indigo-400" };

export default function InsightsCard({ refreshKey }) {
  const { data, error, loading, reload } = useAsync(() => getInsights(), [refreshKey]);
  return (
    <Card>
      <h2 className="text-base font-semibold text-white">Spending Insights</h2>
      {data && <p className="mt-1 text-xs text-slate-500">{data.source === "ai" ? "Generated by an AI model" : "Rule-based analysis of your transactions"}</p>}
      {loading && <Loading />}
      {error && <ErrorMessage error={error} onRetry={reload} />}
      {data && (
        <ul className="mt-4 space-y-3 text-sm text-slate-300" aria-label="Insights">
          {data.insights.map((i) => (
            <li key={i.id} className="flex gap-2" data-severity={i.severity}>
              <span className={DOT[i.severity] ?? DOT.info} aria-hidden="true">•</span>
              {i.message}
            </li>
          ))}
        </ul>
      )}
    </Card>
  );
}
